
"""
Project: LangGraph LLM Token Tracker
File: llm_token_tracker.py

Description:
    A sequential LangGraph workflow that:
    1. Accepts a user question.
    2. Generates an answer using Google Gemini.
    3. Stores the complete AIMessage response.
    4. Extracts input, output, and total token usage.
    5. Displays the final result.

Architecture:
    START -> llm_node -> token_node_counter -> END
"""

# ============================================================
# 1. IMPORT LIBRARIES
# ============================================================

import os

from dotenv import load_dotenv
from typing_extensions import TypedDict, NotRequired

from langchain_core.messages import AIMessage
from langchain_google_genai import ChatGoogleGenerativeAI
from langgraph.graph import StateGraph, START, END


# ============================================================
# 2. LOAD ENVIRONMENT VARIABLES
# ============================================================

# Load environment variables from the .env file.
load_dotenv()

# Validate the Google API key.
if not os.getenv("GOOGLE_API_KEY"):
    raise ValueError(
        "GOOGLE_API_KEY not found. "
        "Please add it to your .env file."
    )


# ============================================================
# 3. INITIALIZE THE LLM
# ============================================================

# Google Gemini model accessed through LangChain.
# temperature=0 encourages more consistent responses.

llm = ChatGoogleGenerativeAI(
    model="gemini-2.5-flash-lite",
    temperature=0
)


# ============================================================
# 4. DEFINE SHARED STATE
# ============================================================

class LLMState(TypedDict):
    """
    Custom TypedDict defining the LangGraph state.

    question:
        User's input question.

    answer:
        Text generated by the LLM.

    response:
        Complete AIMessage containing the model response
        and associated metadata.

    input_tokens:
        Number of input tokens reported by the provider.

    output_tokens:
        Number of generated output tokens.

    total_tokens:
        Total tokens reported by the provider.

    NotRequired:
        These fields may be absent from the initial state.
        Nodes populate them during graph execution.
    """

    question: str

    answer: NotRequired[str]
    response: NotRequired[AIMessage]

    input_tokens: NotRequired[int]
    output_tokens: NotRequired[int]
    total_tokens: NotRequired[int]


# ============================================================
# 5. LLM NODE
# ============================================================

def llm_node(state: LLMState) -> dict:
    """
    Generates an answer using the Gemini LLM.

    Steps:
        1. Extract the question from the state.
        2. Invoke the language model.
        3. Extract the generated text.
        4. Return the answer and complete AIMessage.

    The complete AIMessage is saved so the next node
    can inspect its token usage metadata.
    """

    # Read the question from shared state.
    question = state["question"]

    # Send the question to Gemini.
    response = llm.invoke(question)

    # Extract generated text.
    answer = response.text

    # Return partial state updates.
    return {
        "answer": answer,
        "response": response
    }


# ============================================================
# 6. TOKEN COUNTER NODE
# ============================================================

def token_node_counter(state: LLMState) -> dict:
    """
    Extracts token usage from the AIMessage.

    The LLM provider may attach usage_metadata containing:
        - input_tokens
        - output_tokens
        - total_tokens

    This node reads reported token counts.
    It does not manually calculate tokens.
    """

    # Retrieve the AIMessage stored by llm_node.
    response = state["response"]

    # Access token usage metadata.
    usage = response.usage_metadata or {}

    # Extract individual token counts.
    # Default to zero if metadata is unavailable.
    input_tokens = usage.get("input_tokens", 0)
    output_tokens = usage.get("output_tokens", 0)
    total_tokens = usage.get("total_tokens", 0)

    # Return token counts as state updates.
    return {
        "input_tokens": input_tokens,
        "output_tokens": output_tokens,
        "total_tokens": total_tokens
    }


# ============================================================
# 7. BUILD LANGGRAPH WORKFLOW
# ============================================================

def build_graph():
    """
    Creates and compiles the sequential LangGraph.

    Workflow:
        START
          |
          v
        llm_node
          |
          v
        token_node_counter
          |
          v
         END
    """

    # Initialize graph builder with shared state schema.
    workflow_builder = StateGraph(LLMState)

    # Register nodes.
    workflow_builder.add_node("llm_node", llm_node)

    workflow_builder.add_node(
        "token_node_counter",
        token_node_counter
    )

    # Define execution order using edges.
    workflow_builder.add_edge(START, "llm_node")

    workflow_builder.add_edge(
        "llm_node",
        "token_node_counter"
    )

    workflow_builder.add_edge(
        "token_node_counter",
        END
    )

    # Compile the graph into an executable workflow.
    return workflow_builder.compile()


# ============================================================
# 8. MAIN EXECUTION
# ============================================================

def main():
    """
    Runs the LangGraph workflow with a user question
    and displays the generated answer and token usage.
    """

    # Build the executable graph.
    app = build_graph()

    # Accept a question from the user.
    question = input("\nEnter your question: ").strip()

    # Validate user input.
    if not question:
        print("Please enter a valid question.")
        return

    # Prepare initial state.
    initial_state: LLMState = {
        "question": question
    }

    # Execute the graph.
    # LangGraph passes state updates between nodes.
    try:
        result = app.invoke(initial_state)
    except Exception as error:
        print(f"\nWorkflow execution failed: {error}")
        return

    # Display the final result.
    print("\n" + "=" * 50)
    print("LANGGRAPH LLM TOKEN TRACKER")
    print("=" * 50)

    print("\nQuestion:")
    print(result["question"])

    print("\nGenerated Answer:")
    print(result["answer"])

    print("\n" + "=" * 50)
    print("TOKEN USAGE")
    print("=" * 50)

    print("Input Tokens :", result["input_tokens"])
    print("Output Tokens:", result["output_tokens"])
    print("Total Tokens :", result["total_tokens"])

    if not result["response"].usage_metadata:
        print(
            "\nNote: Token metadata was unavailable. "
            "Zero values are placeholders."
        )

    print("=" * 50)


# ============================================================
# 9. PYTHON ENTRY POINT
# ============================================================

# Execute main() only when this file is run directly.
if __name__ == "__main__":
    main()
